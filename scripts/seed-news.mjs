import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import matter from 'gray-matter';

// Seeds the D1 `news` table from the static `src/content/news/*.mdx` posts.
// Usage:
//   node scripts/seed-news.mjs          # write SQL into .wrangler-tmp/news-seed.sql
//   wrangler d1 execute inflatable-pool-factory-db -c workers/news-worker/wrangler.toml --remote --file=.wrangler-tmp/news-seed.sql

const ROOT = path.resolve(import.meta.dirname, '..');
const DIR = path.join(ROOT, 'src', 'content', 'news');
const OUT = path.join(ROOT, '.wrangler-tmp', 'news-seed.sql');

mkdirSync(path.dirname(OUT), { recursive: true });

const q = (s) => String(s ?? '').replace(/'/g, "''");

const files = readdirSync(DIR)
  .filter((f) => f.endsWith('.mdx'))
  .sort();
const now = Date.now();
const rows = [];

for (const file of files) {
  const raw = readFileSync(path.join(DIR, file), 'utf8');
  const { data, content } = matter(raw);
  const slug = file.replace(/\.mdx$/, '');
  const pub = new Date(data.publishDate).getTime();
  const md = content.trim();
  rows.push(
    `INSERT INTO news (id, slug, title, excerpt, body, image, category, tags, author, publish_date, update_date, draft, metadata_title, metadata_description, created_at, updated_at) VALUES (
  '${q(randomUUID())}',
  '${q(slug)}',
  '${q(data.title)}',
  ${data.excerpt ? `'${q(data.excerpt)}'` : 'NULL'},
  '${q(md)}',
  ${data.image ? `'${q(data.image)}'` : 'NULL'},
  ${data.category ? `'${q(data.category)}'` : 'NULL'},
  '${q(JSON.stringify(data.tags || []))}',
  ${data.author ? `'${q(data.author)}'` : 'NULL'},
  ${Number.isFinite(pub) ? pub : now},
  NULL,
  0,
  ${data.metadata?.title ? `'${q(data.metadata.title)}'` : 'NULL'},
  ${data.metadata?.description ? `'${q(data.metadata.description)}'` : 'NULL'},
  ${now},
  ${now}
);`
  );
}

const sql = `-- Auto-generated by scripts/seed-news.mjs (${files.length} posts)
DELETE FROM news;
${rows.join('\n')}
`;

writeFileSync(OUT, sql, 'utf8');
console.log(`[seed-news] ${files.length} posts -> ${path.relative(ROOT, OUT)}`);
